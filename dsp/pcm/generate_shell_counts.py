"""Generate exact cumulative counts of eight V.34 ring indices.

For 0 <= r_i < M, the number of tuples with sum(r_i) < s is
sum_j (-1)^j C(8,j) C(s+7-j*M,8), retaining terms with s > j*M.
This is inclusion/exclusion on eight bounded nonnegative integers. Python
integers are exact; the largest count, 18**8, fits uint64_t. Include both
empty and full prefixes. Each row has 8*(M-1)+2 entries, so its offset is
4*(M-1)**2-2*(M-1). The generated immutable table occupies 10,080 bytes,
shared across calls, and replaces repeated runtime convolutions.
"""

from math import comb
from pathlib import Path
import sys
import tempfile

if len(sys.argv) != 2:
    sys.exit("usage: generate_shell_counts.py OUTPUT_HEADER")

max_rings = 18
values = []
for rings in range(1, max_rings + 1):
    row = [sum((-1) ** j * comb(8, j) * comb(limit + 7 - j * rings, 8)
               for j in range(9) if limit > j * rings)
           for limit in range(8 * (rings - 1) + 2)]
    assert row[0] == 0 and row[-1] == rings ** 8
    assert all(a <= b for a, b in zip(row, row[1:]))
    values.extend(row)
assert len(values) == 1260
content = ["// SPDX-License-Identifier: BSD-3-Clause",
           "/* Generated by dsp/pcm/generate_shell_counts.py. */",
           "#include <stdint.h>",
           f"enum {{ V34_SHELL_COUNT_MAX_RINGS = {max_rings} }};",
           "static const uint64_t V34_EIGHT_RING_PREFIXES[] = {"]
for start in range(0, len(values), 6):
    content.append("\t" + ", ".join(f"UINT64_C({v})" for v in values[start:start + 6]) + ",")
content.append("};")
target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
# Executable and test builds may request the same header concurrently.
with tempfile.TemporaryDirectory(dir=target.parent) as directory:
    temporary = Path(directory) / target.name
    temporary.write_text("\n".join(content) + "\n", encoding="ascii")
    temporary.replace(target)
