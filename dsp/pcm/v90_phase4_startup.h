#ifndef V90_PHASE4_STARTUP_H
#define V90_PHASE4_STARTUP_H

enum v90_phase4_startup_stage {
	V90_PHASE4_STARTUP_INITIAL,
	V90_PHASE4_STARTUP_CONTINUING,
	V90_PHASE4_STARTUP_COMPLETE,
};

enum v90_phase4_startup_result {
	V90_PHASE4_STARTUP_OK,
	V90_PHASE4_STARTUP_DONE,
	V90_PHASE4_STARTUP_FAILED,
	V90_PHASE4_STARTUP_INVALID_ARGUMENT,
	V90_PHASE4_STARTUP_INVALID_STATE,
	V90_PHASE4_STARTUP_INVALID_PARAMETERS,
	V90_PHASE4_STARTUP_OUT_OF_RANGE,
	V90_PHASE4_STARTUP_CLIPPING_RISK,
	V90_PHASE4_STARTUP_SEQUENCE_MISMATCH,
	V90_PHASE4_STARTUP_NUMERIC_FAILURE,
};

const char *v90_phase4_startup_result_name(
	enum v90_phase4_startup_result result);

#endif /* V90_PHASE4_STARTUP_H */
