"""Generate V.34 pre-emphasis at the modem's 8000 Hz sample clock.

V.34 (10/96) 5.4 defines magnitude in dB against f/symbol_rate. Fit a
16-tap symmetric FIR by binary64 least squares at 1025 equally spaced
frequencies spanning both carriers' specified passbands (carrier +/- 0.45S).
Indices 1..5 rise from 0 dB at 0.2S to 2*index dB at 1.2S. Indices 6..10
are flat through 0.4S, interpolate across the unspecified 0.4S..0.8S gap,
then rise from beta at 0.8S by gamma per 0.4S. Both sides use the same
7.5-sample group delay. Index zero retains the existing identity filter.

Normalize coefficient energy before rounding to nearest, ties to even.
The 16382 norm leaves room for rounding within a Q14 coefficient norm of
16384; line-power calibration owns the absolute transmit level. Native
impulse-response tests check the complete transmitter against the +/-1 dB
templates, including pulse shaping and fixed-point rounding.
"""

import math
from pathlib import Path
import sys
import tempfile


def solve(matrix, rhs):
    """Solve the eight normal equations with partial pivoting."""
    rows = [list(row) + [value] for row, value in zip(matrix, rhs)]
    for column in range(len(rhs)):
        pivot = max(range(column, len(rhs)),
                    key=lambda row: abs(rows[row][column]))
        rows[column], rows[pivot] = rows[pivot], rows[column]
        divisor = rows[column][column]
        if abs(divisor) < 1e-12:
            raise ValueError("singular pre-emphasis fit")
        rows[column] = [value / divisor for value in rows[column]]
        for row in range(len(rhs)):
            if row != column:
                factor = rows[row][column]
                rows[row] = [left - factor * right
                             for left, right in zip(rows[row], rows[column])]
    return [row[-1] for row in rows]


def coefficients(rate, carriers, index):
    matrix = [[0.0] * 8 for _ in range(8)]
    rhs = [0.0] * 8
    low, high = min(carriers) - 0.45, max(carriers) + 0.45
    for sample in range(1025):
        frequency = low + (high - low) * sample / 1024
        if index <= 5:
            gain = 2 * index * max(0, frequency - 0.2)
        else:
            beta, gamma = (index - 5) / 2, index - 5
            gain = (beta * min(1, max(0, (frequency - 0.4) / 0.4))
                    + gamma * max(0, (frequency - 0.8) / 0.4))
        target = 10 ** (gain / 20)
        basis = [2 * math.cos(2 * math.pi * frequency * rate / 8000
                             * (7.5 - tap)) for tap in range(8)]
        for left in range(8):
            rhs[left] += basis[left] * target
            for right in range(8):
                matrix[left][right] += basis[left] * basis[right]
    taps = solve(matrix, rhs)
    taps += taps[::-1]
    scale = 16382 / math.sqrt(sum(value * value for value in taps))
    return [round(value * scale) for value in taps]


if len(sys.argv) != 2:
    sys.exit("usage: generate_preemphasis_profiles.py OUTPUT_HEADER")

content = ["// SPDX-License-Identifier: BSD-3-Clause",
           "/* Generated by dsp/pcm/generate_preemphasis_profiles.py. */",
           "static const int16_t V34_PREEMPHASIS_PROFILES",
           "    [V34_SYMBOL_RATE_COUNT][10][V34_PREEMPHASIS_TAPS] = {"]
for name, rate, carriers in (
    ("2400", 2400, (2 / 3, 3 / 4)),
    ("2743", 19200 / 7, (3 / 5, 2 / 3)),
    ("2800", 2800, (3 / 5, 2 / 3)),
    ("3000", 3000, (3 / 5, 2 / 3)),
    ("3200", 3200, (4 / 7, 3 / 5)),
    ("3429", 24000 / 7, (4 / 7,)),
):
    content.append(f"    [V34_SYMBOL_RATE_{name}] = {{")
    for index in range(1, 11):
        values = coefficients(rate, carriers, index)
        content.append("        { " + ", ".join(map(str, values)) + " },")
    content.append("    },")
content.append("};")

target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
# Application and test builds can generate concurrently.
with tempfile.TemporaryDirectory(dir=target.parent) as directory:
    temporary = Path(directory) / target.name
    temporary.write_text("\n".join(content) + "\n", encoding="ascii")
    temporary.replace(target)
