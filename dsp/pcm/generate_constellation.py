"""Generate the exact V.34 (02/98) 9.1/Figure 5 quarter-superconstellation.

Coordinates are 1 modulo 4. Order by squared magnitude, breaking ties by
largest imaginary coordinate, and retain labels 0..415. Integer arithmetic
is exact. The closest excluded lattice coordinate is -47; its squared
magnitude plus the other axis's minimum squared magnitude exceeds label 415,
so the finite -43..45 search contains every selected point. Generate the
inverse from the same points; UINT16_MAX marks unselected lattice positions.
"""

from pathlib import Path
import sys
import tempfile

if len(sys.argv) != 2:
    sys.exit("usage: generate_constellation.py OUTPUT_HEADER")

coordinates = range(-43, 46, 4)
points = sorted(((i, q) for i in coordinates for q in coordinates),
                key=lambda p: (p[0] ** 2 + p[1] ** 2, -p[1]))[:416]
assert points[-1][0] ** 2 + points[-1][1] ** 2 < 47 ** 2 + 1
labels = {point: label for label, point in enumerate(points)}
content = ["// SPDX-License-Identifier: BSD-3-Clause",
           "/* Generated by dsp/pcm/generate_constellation.py. */",
           "enum { V34_QUARTER_GRID_MIN = -43, V34_QUARTER_GRID_MAX = 45,",
           "       V34_QUARTER_GRID_STEP = 4, V34_QUARTER_GRID_SIDE = 23 };",
           "static const struct v34_grid_point V34_QUARTER_POINTS[] = {"]
content += [f"    {{ {i}, {q} }}," for i, q in points]
content += ["};", "static const uint16_t V34_QUARTER_LABELS",
            "    [V34_QUARTER_GRID_SIDE][V34_QUARTER_GRID_SIDE] = {"]
for q in coordinates:
    content.append("    { " + ", ".join(str(labels.get((i, q), 65535))
                                          for i in coordinates) + " },")
content.append("};")
target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
# Executable and test builds may regenerate the same header concurrently.
with tempfile.TemporaryDirectory(dir=target.parent) as directory:
    temporary = Path(directory) / target.name
    temporary.write_text("\n".join(content) + "\n", encoding="ascii")
    temporary.replace(target)
