"""Generate the 257-point Q15 sine and atan profiles.

Use binary64 sin(pi * index / 256 / 2), scaled by 32768 and truncated.
Values are 0..32768; truncation error is less than one Q15 unit. Rounding
would change 114 endpoints. The native profile digest protects these values.

Use binary64 atan(index / 256), scaled by 32768 and rounded to nearest,
with positive ties rounded up. The Q15 radian words are 0..25736, with at
most half a Q15 unit of rounding error. Both profiles retain their digests.
"""

import math
from pathlib import Path
import sys
import tempfile


if len(sys.argv) != 2:
    sys.exit("usage: generate_phase_profile.py OUTPUT_HEADER")

content = "\n".join([
    "// SPDX-License-Identifier: BSD-3-Clause",
    "/* Generated by dsp/generate_phase_profile.py. */",
    "#include <stdint.h>",
    "",
])
for name, values in (
    ("QUARTER", [int(math.sin(math.pi * index / 256.0 / 2.0) * 32768.0)
                 for index in range(257)]),
    ("ATAN", [int(math.atan(index / 256.0) * 32768.0 + 0.5)
              for index in range(257)]),
):
    rows = ["\t" + ", ".join(map(str, values[index:index + 8])) + ","
            for index in range(0, len(values), 8)]
    content += "\n".join([
        f"static const uint16_t FIXED_PHASE_{name}_Q15[257] = {{",
        *rows, "};", "",
    ])

target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
# Publish atomically: application and test builds can generate concurrently.
with tempfile.TemporaryDirectory(dir=target.parent) as directory:
    temporary = Path(directory) / target.name
    temporary.write_text(content, encoding="ascii")
    temporary.replace(target)
