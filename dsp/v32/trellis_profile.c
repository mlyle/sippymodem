static int32_t arithmetic_shift_right_s32(int32_t value, unsigned shift)
{
	uint32_t magnitude;
	uint32_t rounding;

	if (value >= 0)
		return value >> shift;
	magnitude = (uint32_t)(-(int64_t)value);
	rounding = (UINT32_C(1) << shift) - 1u;
	return -(int32_t)((magnitude + rounding) >> shift);
}

static int16_t wrap_s16(int32_t value)
{
	uint16_t wrapped = (uint16_t)(uint32_t)value;

	return wrapped <= INT16_MAX ? (int16_t)wrapped :
	       (int16_t)((int32_t)wrapped - 65536);
}

static void region_coordinates(
	uint8_t data_bits_per_symbol, int16_t in_phase, int16_t quadrature,
	int32_t *region_i, int32_t *region_q)
{
	if (data_bits_per_symbol == V32_7200_DATA_BITS) {
		*region_i = arithmetic_shift_right_s32(
			(int32_t)in_phase + quadrature, 2);
		*region_q = arithmetic_shift_right_s32(
			(int32_t)quadrature - in_phase, 2);
	} else if (data_bits_per_symbol == V32_12000_DATA_BITS) {
		*region_i = arithmetic_shift_right_s32(
			wrap_s16((int32_t)in_phase + quadrature), 1);
		*region_q = arithmetic_shift_right_s32(
			wrap_s16((int32_t)quadrature - in_phase), 1);
	} else {
		*region_i = in_phase;
		*region_q = quadrature;
	}
}

static size_t grid_coordinate(int32_t value, uint8_t window)
{
	int32_t magnitude = value < 0 ? -value : value;
	size_t coordinate = (size_t)(magnitude + 0x400) >> 11;

	return coordinate < window ? coordinate : (size_t)window - 1u;
}

static bool output_is_separate(
	const struct v32_trellis_profile *profile, const uint8_t *output)
{
	size_t output_size = V32_TRELLIS_PROFILE_CANDIDATES;

	return output != NULL &&
	       !memory_regions_overlap(
		       output, output_size, profile, sizeof(*profile)) &&
	       !memory_regions_overlap(
		       output, output_size, profile->candidate_labels,
		       profile->candidate_label_count) &&
	       !memory_regions_overlap(
		       output, output_size, profile->region_blocks,
		       profile->region_block_count);
}

enum v32_trellis_profile_result v32_trellis_profile_candidates(
	const struct v32_trellis_profile *profile, int16_t in_phase,
	int16_t quadrature,
	uint8_t candidates[V32_TRELLIS_PROFILE_CANDIDATES])
{
	uint8_t next[V32_TRELLIS_PROFILE_CANDIDATES];
	int32_t region_i;
	int32_t region_q;
	size_t grid_i;
	size_t grid_q;
	size_t region_index;
	size_t quadrant;
	size_t base;

	profile = owned_profile(profile);
	if (profile == NULL || !output_is_separate(profile, candidates))
		return V32_TRELLIS_PROFILE_INVALID_ARGUMENT;
	region_coordinates(
		profile->data_bits_per_symbol, in_phase, quadrature,
		&region_i, &region_q);
	grid_i = grid_coordinate(region_i, profile->region_window);
	grid_q = grid_coordinate(region_q, profile->region_window);
	quadrant = region_i < 1 ? (region_q < 1 ? 0x10u : 0x08u) :
		   (region_q > 0 ? 0x00u : 0x18u);
	region_index = grid_i + (size_t)profile->region_window *
		(grid_q + (grid_i < grid_q ? profile->region_window : 0u));
	if (region_index >= profile->region_block_count)
		return V32_TRELLIS_PROFILE_INVALID_ARGUMENT;
	base = (size_t)profile->region_blocks[region_index] *
		V32_TRELLIS_PROFILE_REGION_BLOCK_LABELS + quadrant;
	if (base + V32_TRELLIS_PROFILE_CANDIDATES >
	    profile->candidate_label_count)
		return V32_TRELLIS_PROFILE_INVALID_ARGUMENT;
	memcpy(next, profile->candidate_labels + base, sizeof(next));
	memcpy(candidates, next, sizeof(next));
	return V32_TRELLIS_PROFILE_OK;
}
